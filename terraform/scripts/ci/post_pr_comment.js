/**
 * Post or update collapsible Terraform plan comment on GitHub PRs.
 * Path: terraform/scripts/ci/post_pr_comment.js
 */

module.exports = async ({ github, context, core }) => {
  const stage = process.env.STAGE_DIR || 'terraform';
  const projectId = process.env.PROJECT_ID || 'unknown';
  const commitSha = (
    process.env.COMMIT_SHA ||
    (context.payload && context.payload.pull_request && context.payload.pull_request.head && context.payload.pull_request.head.sha) ||
    context.sha ||
    ''
  ).substring(0, 7);
  const planOutcome = process.env.PLAN_OUTCOME;
  const fmtOutcome = process.env.FMT_OUTCOME;
  const initOutcome = process.env.INIT_OUTCOME;
  const planText = process.env.PLAN_TEXT;
  const identifier = `<!-- tf-plan-comment:${stage} -->`;

  if (!context || !context.issue || !context.issue.number) {
    if (core && core.warning) {
      core.warning('No pull request issue context found. Skipping PR comment.');
    }
    return;
  }

  let displayPlan = planText;
  if (!displayPlan) {
    if (fmtOutcome === 'failure') {
      displayPlan = 'Terraform format check failed (`terraform fmt -check`). Please format your files and push updates.';
    } else if (initOutcome === 'failure') {
      displayPlan = 'Terraform init failed (`terraform init`). Check backend and provider configurations.';
    } else if (planOutcome === 'failure') {
      displayPlan = 'Terraform plan failed. Please inspect the workflow execution log for detailed error output.';
    } else {
      displayPlan = 'No plan output available.';
    }
  } else if (displayPlan.length > 60000) {
    displayPlan =
      displayPlan.substring(0, 60000) +
      '\n\n... [Plan output truncated due to GitHub comment size limit (60K chars). Check CI log for full output]';
  }

  const isSuccess = fmtOutcome === 'success' && initOutcome === 'success' && planOutcome === 'success';
  const statusEmoji = isSuccess ? '✅ Plan succeeded' : '❌ Plan failed';
  const fence = displayPlan.includes('```') ? '````' : '```';

  const body = [
    identifier,
    `### 🪐 Terraform Plan: \`${stage}\``,
    '',
    `- **Project ID**: \`${projectId}\``,
    `- **Commit**: \`${commitSha}\``,
    `- **Status**: ${statusEmoji}`,
    '',
    '<details>',
    '<summary>📋 Click to expand Terraform Plan output</summary>',
    '',
    `${fence}terraform`,
    displayPlan,
    fence,
    '',
    '</details>',
    '',
    `*Automated plan generated by [Terraform GitOps CI](${context.serverUrl}/${context.repo.owner}/${context.repo.repo}/actions/runs/${context.runId})*`,
  ].join('\n');

  const comments = await (github.paginate
    ? github.paginate(github.rest.issues.listComments, {
        owner: context.repo.owner,
        repo: context.repo.repo,
        issue_number: context.issue.number,
      })
    : github.rest.issues
        .listComments({
          owner: context.repo.owner,
          repo: context.repo.repo,
          issue_number: context.issue.number,
        })
        .then((res) => res.data || []));

  const existingComment = comments.find((c) => c.body && c.body.includes(identifier));

  if (existingComment) {
    await github.rest.issues.updateComment({
      owner: context.repo.owner,
      repo: context.repo.repo,
      comment_id: existingComment.id,
      body: body,
    });
    if (core && core.info) {
      core.info(`Updated existing plan comment for ${stage} (comment ID: ${existingComment.id})`);
    }
    return { action: 'updated', comment_id: existingComment.id };
  } else {
    const created = await github.rest.issues.createComment({
      owner: context.repo.owner,
      repo: context.repo.repo,
      issue_number: context.issue.number,
      body: body,
    });
    if (core && core.info) {
      core.info(`Created new plan comment for ${stage} (comment ID: ${created.data.id})`);
    }
    return { action: 'created', comment_id: created.data.id };
  }
};
